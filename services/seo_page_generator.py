def add_to_sitemap(slug, priority="0.6", changefreq="weekly"):
    """Appends one <url> entry before </urlset>. Idempotent -- skips (and
    returns False) if the URL is already present, so it's safe to call
    again for a page that already has a sitemap entry."""
    url = f"https://www.xfinlab.com/{slug}.html"
    if not os.path.exists(SITEMAP_PATH):
        return False
    text = open(SITEMAP_PATH, encoding="utf-8").read()
    if url in text:
        return False
    entry = f"""  <url>
    <loc>{url}</loc>
    <changefreq>{changefreq}</changefreq>
    <priority>{priority}</priority>
  </url>
</urlset>"""
    text = text.replace("</urlset>", entry)
    with open(SITEMAP_PATH, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def create_ticker_page(ticker, company_name, category="stock", related=None, force=False):
    """Full pipeline: validate slug -> render -> write file -> add to
    sitemap -> record in registry. Refuses to overwrite an existing file
    unless force=True (force is intentionally not exposed via the admin
    API -- it exists only for local re-generation during development, so
    a mistyped admin request can never clobber a live page)."""
    slug = _slugify(ticker)
    if not slug or not re.match(r"^[a-z0-9\-]{1,15}$", slug):
        raise ValueError(f"Invalid ticker slug: {ticker!r}")
    path = os.path.join(REPO_ROOT, f"{slug}.html")
    if os.path.exists(path) and not force:
        raise FileExistsError(f"{slug}.html already exists")

    html = generate_page(ticker, company_name, category, related)
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)

    add_to_sitemap(slug)

    reg = _registry()
    reg[slug] = {
        "ticker": ticker.upper(),
        "company_name": company_name,
        "category": category,
        "created": date.today().isoformat(),
    }
    _save_registry(reg)
    return {"slug": slug, "path": f"{slug}.html", "sitemap_added": True}
