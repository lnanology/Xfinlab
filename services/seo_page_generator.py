def _registry():
    if not os.path.exists(REGISTRY_PATH):
        return {}
    try:
        with open(REGISTRY_PATH, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def _save_registry(reg):
    os.makedirs(os.path.dirname(REGISTRY_PATH), exist_ok=True)
    with open(REGISTRY_PATH, "w", encoding="utf-8") as f:
        json.dump(reg, f, ensure_ascii=False, indent=2)


def list_existing_pages():
    """Read-only: every *.html in the repo root that looks like a
    ticker/comparison SEO page (i.e. not one of the core site pages)."""
    pages = []
    for path in sorted(glob.glob(os.path.join(REPO_ROOT, "*.html"))):
        name = os.path.basename(path)
        if name in _CORE_PAGES:
            continue
        pages.append(name[:-5])  # strip ".html"
    reg = _registry()
    return {
        "count": len(pages),
        "pages": pages,
        "generated_by_engine": len(reg),
    }


def _slugify(ticker):
    return re.sub(r"[^a-z0-9\-]", "", ticker.lower())


def _parse_autocomplete_assets():
    """Best-effort regex extraction of {symbol,name,type,popularity} from
    js/autocomplete.js's ASSETS array -- reuses the site's existing ticker
    universe rather than maintaining a second registry. Not a full JS
    parser; tolerant of extra fields per object (aliases, logo, etc.)."""
    if not os.path.exists(AUTOCOMPLETE_JS_PATH):
        return []
    text = open(AUTOCOMPLETE_JS_PATH, encoding="utf-8").read()
    pattern = re.compile(
        r'\{symbol:"(?P<symbol>[^"]+)",name:"(?P<name>[^"]+)",type:"(?P<type>[^"]+)"'
        r'[^}]*?popularity:(?P<popularity>\d+)'
    )
    out = []
    seen = set()
    for m in pattern.finditer(text):
        sym = m.group("symbol")
        if sym in seen:
            continue
        seen.add(sym)
        out.append({
            "symbol": sym,
            "name": m.group("name"),
            "type": m.group("type"),
            "popularity": int(m.group("popularity")),
        })
    return out


def suggest_candidates(limit=30):
    """Assets from the site's own autocomplete universe that don't have a
    landing page yet, ranked by popularity (most-searched-for first). This
    is the "AI" part of the AI SEO Engine in the sense that matters for a
    one-person team: it tells you what to build next instead of guessing."""
    existing = {p.lower() for p in list_existing_pages()["pages"]}
    assets = _parse_autocomplete_assets()
    out = [a for a in assets if _slugify(a["symbol"]) not in existing]
    out.sort(key=lambda a: -a["popularity"])
    return out[:limit]


