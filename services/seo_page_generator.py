"""
Growth OS Phase 1 -- AI SEO Engine.

Turns XFINLAB's already-live per-ticker SEO landing pages (see aapl.html,
built across tasks #453-502) into a repeatable, admin-controlled pipeline
instead of one-off hand-written HTML. Three pieces:

1. list_existing_pages() -- read-only glob of the ticker/comparison pages
   already on disk (safe: never writes anything).
2. suggest_candidates() -- cross-references js/autocomplete.js's ~400-asset
   universe (the same dataset used site-wide for ticker search) against
   pages that already exist, returning assets that don't have a landing
   page yet, ranked by the `popularity` score autocomplete.js already
   carries per asset.
3. create_ticker_page() -- renders a new page from the same template
   family as aapl.html (dark theme, FAQPage+BreadcrumbList JSON-LD, live
   price/trend fetch, related-assets cross-links), writes it, and appends
   it to sitemap.xml. Never overwrites an existing file.

Nothing here runs automatically on a schedule -- every generation is
triggered by an explicit admin action (api/admin.py's /admin/seo/*
endpoints), per the user's own requirement: "後台加入可控制" (build it,
but keep it admin-controllable rather than silently autonomous).
"""
